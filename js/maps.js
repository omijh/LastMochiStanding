export function getMapConfig(mapId) {
  return MAPS[mapId] || MAPS.cafe;
}

export function pickMapId(selection, prevMapId = null) {
  if (selection && MAPS[selection]) {
    return selection;
  }
  const pool = prevMapId ? MAP_ORDER.filter((id) => id !== prevMapId) : MAP_ORDER;
  const choices = pool.length > 0 ? pool : MAP_ORDER;
  return choices[Math.floor(Math.random() * choices.length)];
}
